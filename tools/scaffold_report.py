"""
scaffold_report.py - create analysis/<report>/ with ready-to-fill plan, analysis, checks and
report scripts, so agents write only the parts specific to the question.

Used by the Quick Report agent (fast path) and optionally by the Analyst (full flow).
The generated scripts already handle loading, logging, output files, the standard validation
checks and an automatic report layout; each has a small "FILL IN" block. It also writes the
report manifest (report.json) that registers the report's inputs and domain packs.

Treasury-aware defaults (from the profile's confirmed annotations):
  - additive measure (flows: payments, interest)      -> headline = sum over the rows in scope
  - semi-additive measure (stocks: balances, positions, outstanding) -> headline taken at ONE
    as-of date (latest date in scope by default), never summed across dates
  - non-additive measure (rates, ratios)               -> refused as the headline measure;
    use the amount it applies to and compute a weighted average in the FILL IN block
  - a currency column in the main input                -> a check that the headline is in a single
    currency, or that a conversion step was added (set CONVERTED = True once it is)

Search first so you don't build a duplicate:  python tools/reports.py find "<question words>"

Usage (names are illustrative):
  python tools/scaffold_report.py cash_position_daily \
      --source bank_balances:Balances --measure "Closing Balance" \
      --title "Daily cash position" --question "What is the cash position by entity and bank?" --quick

  --source       source_id:sheet (preferred - always reads the current file of a recurring source)
                 or profile_name:sheet for a one-off file. A profile that belongs to a registered
                 source is converted to that source automatically.
                 Repeat for each input; the first is the main table.
  --measure      column of the main measure in the first input
  --as-of-column date column that says WHEN the position is (reporting / snapshot / balance date).
                 Default: a date column with a single value (a snapshot), else one named like
                 "reporting/as of/snapshot/position/balance date", else the first date column.
  --bucket-column date column to bucket the position BY (maturity, due, repricing date), measured
                 from the as-of date. Adds cumulative "next N days" windows and a by-year table to
                 analysis.py, and matching independent checks to checks.py. Never the as-of column.
  --currency     label prefix for amounts in the report, e.g. "EUR " (default: none)
  --question, --owner, --schedule, --tag   recorded in report.json
  --quick        mark as a fast-path report (review level "quick")
  --force        overwrite existing files
"""
