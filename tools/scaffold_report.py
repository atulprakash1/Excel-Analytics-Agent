def py(v) -> str:
    return json.dumps(v).replace("null", "None")


def pick_as_of(columns: list[dict], roles: dict, exclude: str = "") -> str:
    """A single-value date column is a snapshot date; then a date named like one; then the first date."""
    dates = [c for c in columns if roles.get(c["name"]) == "date" and c["name"] != exclude]
    for pick in (lambda c: c.get("distinct") == 1, lambda c: AS_OF_NAME.search(c["name"]), lambda c: True):
        hit = next((c["name"] for c in dates if pick(c)), None)
        if hit:
            return hit
    return ""


